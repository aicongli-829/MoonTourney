#!/usr/bin/env python3
"""Generate MoonBit language-definition data from tokei's languages.json.

Source: https://github.com/XAMPPRocky/tokei/tree/v15.0.0
Run from repo root:  python3 tools/gen_lang_data.py > lang/data.mbt
"""
import json, sys

def mstr(s):
    """MoonBit string literal — same escape syntax as JSON."""
    return json.dumps(s, ensure_ascii=False)

def main():
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    src = sys.argv[1] if len(sys.argv) > 1 else "vendor/tokei-v15.0.0/languages.json"
    data = json.load(open(src, encoding="utf-8"))["languages"]
    out = []
    out.append("// GENERATED by tools/gen_lang_data.py from tokei's languages.json.")
    out.append("// Source data: https://github.com/XAMPPRocky/tokei (Apache-2.0 OR MIT).")
    out.append("// Do not edit by hand; regenerate instead.")
    out.append("")
    out.append("///|")
    out.append("let all_langs : Array[LangDef] = [")
    for key in sorted(data.keys()):
        v = data[key]
        name = v.get("name", key)
        lc = ", ".join(mstr(x) for x in v.get("line_comment", []))
        mlc = ", ".join(f'({mstr(a)}, {mstr(b)})' for a, b in v.get("multi_line_comments", []))
        q = ", ".join(f'({mstr(a)}, {mstr(b)})' for a, b in v.get("quotes", []))
        vq = ", ".join(f'({mstr(a)}, {mstr(b)})' for a, b in v.get("verbatim_quotes", []))
        dq = ", ".join(f'({mstr(a)}, {mstr(b)})' for a, b in v.get("doc_quotes", []))
        imp = ", ".join(mstr(x) for x in v.get("important_syntax", []))
        literate = "true" if v.get("literate") else "false"
        nested = "true" if (v.get("nested") or v.get("nested_comments")) else "false"
        shb = ", ".join(mstr(x) for x in v.get("shebangs", []))
        ext = ", ".join(mstr(x).lower() for x in v.get("extensions", []))
        fnames = ", ".join(mstr(x).lower() for x in v.get("filenames", []))
        out.append("  {")
        out.append(f'    key: {mstr(key)},')
        out.append(f'    name: {mstr(name)},')
        out.append(f'    line_comments: [{lc}],')
        out.append(f'    block_comments: [{mlc}],')
        out.append(f'    quotes: [{q}],')
        out.append(f'    verbatim_quotes: [{vq}],')
        out.append(f'    doc_quotes: [{dq}],')
        out.append(f'    important_syntax: [{imp}],')
        out.append(f'    literate: {literate},')
        out.append(f'    nested: {nested},')
        out.append(f'    shebangs: [{shb}],')
        out.append(f'    extensions: [{ext}],')
        out.append(f'    filenames: [{fnames}],')
        out.append("  },")
    out.append("]")
    print("\n".join(out))

if __name__ == "__main__":
    main()
